def assemble_periodic_table():
    assembly = ''
    last_line, last_column = 1 , 1
    for element, (line, column) in chem_elements:
        if(line>last_line):
            last_column = 1
            assembly += '\n'
        assembly += '   ' * column - last_column
        last_column = last_column
